// Bake OpenStreetMap building footprints over the town-context area (CONTEXT_BBOX in
// index.html) into assets/buildings-context.js (window.RASCH_BUILDINGS) for the 3D-buildings
// layer. Heights: OSM `height` (m) when tagged, else `building:levels` × 3.2 m (+1 m roof),
// else an ESTIMATE by building type — flagged per building (`est: 1`), because only a few
// percent of the footprints here carry any height tag. Orientation context, not survey data.
//
// Usage: node scripts/bake-buildings.mjs                 (queries Overpass; network required)
//        node scripts/bake-buildings.mjs --from file.json (re-bake from a saved Overpass result)
import { readFileSync, writeFileSync } from 'node:fs';

const BBOX = { west: 6.118, east: 6.162, south: 49.652, north: 49.6708 };
const QUERY = `[out:json][timeout:170];(way(${BBOX.south},${BBOX.west},${BBOX.north},${BBOX.east})[building];);out tags geom;`;
const ENDPOINTS = ['https://overpass.kumi.systems/api/interpreter', 'https://overpass-api.de/api/interpreter'];

async function fetchOverpass() {
  for (const url of ENDPOINTS) {
    try {
      const res = await fetch(url, { method: 'POST', body: new URLSearchParams({ data: QUERY }) });
      if (res.ok) return await res.json();
      console.warn('overpass', url, 'http', res.status);
    } catch (e) { console.warn('overpass', url, e.message); }
  }
  throw new Error('all Overpass endpoints failed');
}

// Typical storey counts by OSM building=* value (estimate only).
const LEVELS = {
  house: 2, detached: 2, semidetached_house: 2, terrace: 2, residential: 2.5, apartments: 4,
  farm: 2, bungalow: 1, commercial: 3, retail: 2, office: 4, industrial: 2.5, warehouse: 2.5,
  school: 3, public: 3, civic: 3, government: 3, hospital: 4, hotel: 4, church: 5, chapel: 3,
  garage: 1, garages: 1, shed: 1, carport: 1, roof: 1, hut: 1, greenhouse: 1, service: 1,
  kiosk: 1, barn: 2, farm_auxiliary: 1.5, stable: 1.5, transformer_tower: 2, construction: 2
};
function heightOf(t) {
  const num = v => { const n = parseFloat(String(v).replace(',', '.')); return Number.isFinite(n) ? n : null; };
  const h = num(t.height);
  if (h != null && h > 1 && h < 120) return { h, est: 0 };
  const l = num(t['building:levels']);
  if (l != null && l > 0 && l < 40) return { h: l * 3.2 + 1, est: 0 };
  const lv = LEVELS[t.building] ?? 2;
  return { h: Math.round((lv * 3.2 + 1) * 10) / 10, est: 1 };
}

const args = process.argv.slice(2);
const from = args.indexOf('--from') >= 0 ? args[args.indexOf('--from') + 1] : null;
const data = from ? JSON.parse(readFileSync(from, 'utf8')) : await fetchOverpass();

const out = [];
for (const e of data.elements || []) {
  if (e.type !== 'way' || !e.geometry || e.geometry.length < 4) continue;
  const t = e.tags || {};
  if (t.building === 'no' || t['building:part']) continue;
  const ring = e.geometry.map(p => [+p.lon.toFixed(6), +p.lat.toFixed(6)]);
  // drop the closing duplicate vertex
  const [a, b] = [ring[0], ring[ring.length - 1]];
  if (a[0] === b[0] && a[1] === b[1]) ring.pop();
  if (ring.length < 3) continue;
  const { h, est } = heightOf(t);
  out.push({ h, est, r: ring.flat() });
}
const doc = {
  _doc: 'GENERATED by scripts/bake-buildings.mjs — OpenStreetMap building footprints (© OpenStreetMap contributors, ODbL) over the town-context bbox. h = height in metres (OSM height / levels; est=1 marks a type-based estimate). r = flat [lon,lat,…] outer ring.',
  bbox: BBOX, count: out.length, estimated: out.filter(b => b.est).length, buildings: out
};
writeFileSync(new URL('../assets/buildings-context.js', import.meta.url),
  '// GENERATED by scripts/bake-buildings.mjs — DO NOT EDIT. Run `node scripts/bake-buildings.mjs`.\n' +
  'window.RASCH_BUILDINGS = ' + JSON.stringify(doc) + ';\n');
console.log(`› wrote assets/buildings-context.js — ${out.length} buildings (${doc.estimated} with estimated height)`);
